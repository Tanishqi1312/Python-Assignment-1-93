"""Assignment 1 - Question 18
Calculate volume of cube and cuboid.
Run this file directly in VS Code.
"""

side = float(input("Cube side: "))
l = float(input("Cuboid length: "))
b = float(input("Cuboid breadth: "))
h = float(input("Cuboid height: "))
print("Cube volume =", side ** 3)
print("Cuboid volume =", l * b * h)
